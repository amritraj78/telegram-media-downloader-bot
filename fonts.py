# Unicode Font Converter for Aesthetic Small Caps UI

FONT_MAP = {
    'a': 'ᴀ', 'b': 'ʙ', 'c': 'ᴄ', 'd': 'ᴅ', 'e': 'ᴇ', 'f': 'ғ', 'g': 'ɢ',
    'h': 'ʜ', 'i': 'ɪ', 'j': 'ᴊ', 'k': 'ᴋ', 'l': 'ʟ', 'm': 'ᴍ', 'n': 'ɴ',
    'o': 'ᴏ', 'p': 'ᴘ', 'q': 'ǫ', 'r': 'ʀ', 's': 's', 't': 'ᴛ', 'u': 'ᴜ',
    'v': 'ᴠ', 'w': 'ᴡ', 'x': 'x', 'y': 'ʏ', 'z': 'ᴢ',
    'A': 'ᴀ', 'B': 'ʙ', 'C': 'ᴄ', 'D': 'ᴅ', 'E': 'ᴇ', 'F': 'ғ', 'G': 'ɢ',
    'H': 'ʜ', 'I': 'ɪ', 'J': 'ᴊ', 'K': 'ᴋ', 'L': 'ʟ', 'M': 'ᴍ', 'N': 'ɴ',
    'O': 'ᴏ', 'P': 'ᴘ', 'Q': 'ǫ', 'R': 'ʀ', 'S': 's', 'T': 'ᴛ', 'U': 'ᴜ',
    'V': 'ᴠ', 'W': 'ᴡ', 'X': 'x', 'Y': 'ʏ', 'Z': 'ᴢ'
}


def to_stylish(text: str) -> str:
    """Converts regular Latin text into stylish aesthetic small-caps font."""
    result = []
    in_tag = False
    in_entity = False

    # Avoid converting HTML tags like <b>, </b>, <code>, <a>
    for char in text:
        if char == '<':
            in_tag = True
            result.append(char)
            continue
        elif char == '>':
            in_tag = False
            result.append(char)
            continue

        if char == '&':
            in_entity = True
            result.append(char)
            continue
        elif in_entity and char == ';':
            in_entity = False
            result.append(char)
            continue

        if in_tag or in_entity:
            result.append(char)
        else:
            result.append(FONT_MAP.get(char, char))

    return "".join(result)
